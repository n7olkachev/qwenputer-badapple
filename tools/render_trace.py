"""Render the video next to the token stream that produces it: the frame (left) and the trace
tokens the machine emitted for it (right), BYTE tokens shown as the 8 pixels they carry.

usage: uv run --project qwenputer/experimental/riscv python tools/render_trace.py
           [--out build/badapple_trace.mp4] [--seconds N] [--start S]
Needs build/out.bin and build/trace.u32 from run_ref.py.
"""
import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "qwenputer/experimental/riscv"))
from chipformer.rv import spec as S  # noqa: E402

W, H, FPS, FB = 80, 60, 12, 600
CW, CH = 1280, 720
SCALE = 8
FRAME_X, FRAME_Y = 40, 150
PANE_X, PANE_Y, PANE_W = 730, 150, 510
LINES = 21
FONT = "/System/Library/Fonts/Menlo.ttc"
BG, FG, DIM, HI, PIX_ON, PIX_OFF = (12, 12, 14), (230, 230, 230), (110, 110, 120), (120, 220, 140), (240, 240, 240), (50, 50, 56)


def fam_ranges():
    out = {}
    for nm, (base, size) in S.FAMILIES.items():
        out[nm] = (base, base + size)
    for nm, t in S.CONTROLS.items():
        out[nm] = (t, t + 1)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "build/badapple_trace.mp4"))
    ap.add_argument("--seconds", type=float, default=None)
    ap.add_argument("--start", type=float, default=0.0)
    ap.add_argument("--audio", default=str(ROOT / "video/badapple.mp4"))
    a = ap.parse_args()

    out = (ROOT / "build/out.bin").read_bytes()
    trace = np.fromfile(ROOT / "build/trace.u32", dtype=np.uint32)
    fr = fam_ranges()
    b0, b1 = fr["BYTE"]
    byte_pos = np.nonzero((trace >= b0) & (trace < b0 + 256))[0]
    assert len(byte_pos) == len(out)
    final = np.zeros(len(trace), dtype=bool)
    for nm in S.FINAL - {"R"}:
        lo, hi = fr[nm]
        final |= (trace >= lo) & (trace < hi)
    instr_cum = np.cumsum(final)
    n_frames = len(out) // FB
    f0 = int(a.start * FPS)
    f1 = n_frames if a.seconds is None else min(n_frames, f0 + int(a.seconds * FPS))

    font = ImageFont.truetype(FONT, 17)
    small = ImageFont.truetype(FONT, 14)
    big = ImageFont.truetype(FONT, 26)
    line_h = 22
    cmd = ["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{CW}x{CH}",
           "-r", str(FPS), "-i", "-", "-ss", str(a.start), "-i", a.audio, "-map", "0:v", "-map", "1:a?",
           "-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p",
           "-c:a", "aac", "-b:a", "160k", "-shortest", a.out]
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    for f in range(f0, f1):
        im = Image.new("RGB", (CW, CH), BG)
        d = ImageDraw.Draw(im)
        d.text((40, 36), "Bad Apple!! on the Qwenputer", font=big, fill=FG)
        d.text((40, 76), "a RISC-V CPU compiled as 11 extra transformer layers ahead of Qwen's 32 decodes the video;", font=small, fill=DIM)
        d.text((40, 96), "every token on the right is the machine running, every BYTE token is 8 pixels", font=small, fill=DIM)
        # the frame
        fb = np.unpackbits(np.frombuffer(out[f * FB:(f + 1) * FB], np.uint8)).reshape(H, W) * 255
        fim = Image.fromarray(fb.astype(np.uint8), "L").resize((W * SCALE, H * SCALE), Image.NEAREST)
        im.paste(fim, (FRAME_X, FRAME_Y))
        d.rectangle([FRAME_X - 1, FRAME_Y - 1, FRAME_X + W * SCALE, FRAME_Y + H * SCALE], outline=(60, 60, 66))
        # the tokens ending at this frame's last byte
        end = byte_pos[(f + 1) * FB - 1]
        toks = trace[max(0, end - LINES + 1):end + 1]
        y = PANE_Y
        for t in toks:
            t = int(t)
            nm = S.name(t)
            if b0 <= t < b0 + 256:
                v = t - b0
                d.text((PANE_X, y), f"BYTE {v:02x}", font=font, fill=HI)
                for i in range(8):
                    on = v >> (7 - i) & 1
                    x = PANE_X + 120 + i * 18
                    d.rectangle([x, y + 3, x + 14, y + 17], fill=PIX_ON if on else PIX_OFF)
            else:
                d.text((PANE_X, y), nm, font=font, fill=DIM)
            y += line_h
        d.rectangle([PANE_X - 12, PANE_Y - 10, PANE_X + PANE_W, PANE_Y + LINES * line_h], outline=(60, 60, 66))
        # stats
        toks_so_far, instr = end + 1, int(instr_cum[end])
        d.text((40, 648), f"frame {f + 1:4d} / {n_frames}   {toks_so_far:,} tokens   {instr:,} instructions",
               font=font, fill=FG)
        d.text((40, 674), "video: 250 KB ZX0 in the DROM + ROM (as lui immediates)   RAM: a 26 KB ring   "
               "", font=small, fill=DIM)
        d.text((40, 694), "19.06M tokens; 86K generated by the compiled layers so far, 0 mismatches   "
               "audio: the original song, dubbed; the machine outputs pixels only", font=small, fill=DIM)
        p.stdin.write(im.tobytes())
    p.stdin.close()
    p.wait()
    print("wrote", a.out, f"({f1 - f0} frames)")


if __name__ == "__main__":
    main()
